abstract class Explanation_of_AbstractClass_AbstractMethod {
	
	/*
	 * Abstract class is a class which has only declarlared with abstract key worr before the class name 
	 * We cannot create a object for abstract class and access it like normal class
	 * Abstract class is like a set of rules which must be followed by chile class that implemets the abstract class.
	 * 
	 * A child class inheriting  abstract class must override the abstract methods, if not the child class must declare itself as abstract class .
	 * A abstract class can contain instance variable , static variable , final variable, 
	 * 	constructor , Abstract methods (nobody), normal methods ,static methods , final methods.
	 * 
	 */
	
	/*
	 * An abstract method is a method that has only declaration (signature) but NO body (no implementation).
	 * It tells what to do and not how to do 
	 * 
	 * Syntax: abstract return type  method_name (parameter);
	 * 
	 * Abstract method should be present inside  abstract class.
	 * 
	 * 
	 * A abstract method cannot be private , if it is private a child class cannot access it and override it .
	 * Cannot be static , because static belongs to class not an object .
	 * cannot be final , because final can not be overrided .
	 * Abstract method can have  paramethers and retun types , void as return type , or
	 */
	
	

}
